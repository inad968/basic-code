package com.itheima.logicoperator;

public class LogicoperatorDemo1 {
    public static void main(String[] args) {
        int a= 10;
        int b= 20;
        boolean result = ++a < 5 && ++b < 5;
        System.out.println("result:" + result);
        System.out.println("a:" + a);
        System.out.println("b:" + b);
    }
}








